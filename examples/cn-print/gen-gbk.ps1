# gen-gbk.ps1 — UTF-8 中文文本源 -> FLINT 纯 ASCII 逐字节十六进制表（可复用生成器）
#
# 为什么要它：FLINT 的源文件**不能含非 ASCII 字节**（没有真正的字符串类型、没有 UTF-8 运行时）
#   ⇒ 中文只能用 "\xNN" 逐字节装填 GBK(936)。手抄码点极易错，所以由脚本从 UTF-8 文本源生成，
#   并在写完后**自证「生成物里 >127 的字节数 = 0」**（这一条就是这套做法的判据）。
# 本文件含中文注释 ⇒ **必须带 UTF-8 BOM**：PS 5.1 读无 BOM 文件时按 GBK 解码，中文注释会被
#   撕成半个字符，报一堆指向无辜行的假语法错（本仓踩过多次，见 ps-script-safety 纪律）。
# 用法（改完 text.txt 重跑即可；examples\cn-print\build.ps1 会自动调它）：
#   powershell -NoProfile -ExecutionPolicy Bypass -File examples\cn-print\gen-gbk.ps1
# 输入 text.txt（UTF-8，TAB 分隔）：<函数名>\t<文本>，每行生成一条
#   char *<函数名>() { return "\xNN..."; }
# 输出 cn_gen.fl（纯 ASCII，交给 FLINT 编译）
param(
  [string]$In  = "",
  [string]$Out = ""
)
$ErrorActionPreference = 'Stop'
if ($In  -eq "") { $In  = Join-Path $PSScriptRoot 'text.txt' }
if ($Out -eq "") { $Out = Join-Path $PSScriptRoot 'cn_gen.fl' }

# 936 = GBK：Windows 中文控制台 / 记事本的字节口径，也是 FLINT 侧唯一能用的"中文编码"
$gbk = [System.Text.Encoding]::GetEncoding(936)

# 一个字符串 -> FLINT 字面量写法：可打印 ASCII 原样；引号/反斜杠转义；其余（含全部中文）走 \xNN
function Esc-Lit([string]$s) {
  $bytes = $gbk.GetBytes($s)
  $sb = New-Object System.Text.StringBuilder
  foreach ($b in $bytes) {
    if ($b -eq 0x22) { [void]$sb.Append('\"') }
    elseif ($b -eq 0x5C) { [void]$sb.Append('\\') }
    elseif ($b -ge 0x20 -and $b -le 0x7E) { [void]$sb.Append([char]$b) }
    else { [void]$sb.Append('\x' + $b.ToString('X2')) }
  }
  return $sb.ToString()
}

if (-not (Test-Path -LiteralPath $In)) { throw "找不到文本源：$In" }
$lines = Get-Content -LiteralPath $In -Encoding UTF8
$buf = @()
$buf += '// cn_gen.fl -- AUTO-GENERATED by examples\cn-print\gen-gbk.ps1 (do not edit by hand)'
$buf += '// source: examples\cn-print\text.txt (UTF-8); text is emitted as GBK(936) bytes: \xNN'
$buf += '// why: FLINT has no non-ASCII literal and no UTF-8 runtime, so a Chinese label has to be'
$buf += '//      spelled out one byte at a time. This file must stay pure ASCII -- the generator'
$buf += '//      counts the bytes > 127 after writing and throws if it finds any.'
$n = 0
foreach ($ln in $lines) {
  if ([string]::IsNullOrWhiteSpace($ln)) { continue }
  $p = $ln -split "`t"
  if ($p.Count -lt 2) { throw "行格式不对（需要 TAB 分隔的 <函数名>\t<文本>）：$ln" }
  $fn  = $p[0].Trim()
  $txt = $p[1]
  $lit = Esc-Lit $txt
  $buf += "char *$fn() { return `"$lit`"; }"
  $bl  = $gbk.GetBytes($txt)
  $hex = (($bl | ForEach-Object { $_.ToString('X2') }) -join ' ')
  Write-Host ("  {0,-16} {1,2} bytes  {2}" -f $fn, $bl.Length, $hex)
  $n = $n + 1
}
if ($n -eq 0) { throw "文本源里没有任何条目：$In" }
[System.IO.File]::WriteAllText($Out, ($buf -join "`r`n") + "`r`n", (New-Object System.Text.ASCIIEncoding))

# 自证：生成物必须是纯 ASCII（>127 的字节一个都不许有）
$gb = [System.IO.File]::ReadAllBytes($Out)
$hi = 0
foreach ($b in $gb) { if ($b -gt 127) { $hi++ } }
Write-Host ("生成: {0}（{1} 条目，{2} 字节，其中 >127 的字节 = {3}）" -f $Out, $n, $gb.Length, $hi)
if ($hi -ne 0) { throw "生成物里出现非 ASCII 字节：$hi 个" }
