// sprite2fl2.js -- second playable character's sprite sheet (ASCII grid) -> FLINT byte table
// (games\huiye\hero2_sprite_data.fl)
//
// Copied from tools\sprite2fl.js -- the original tool and its output
// (games\huiye\sprite_data.fl) are NOT touched by this copy.
//
// Usage:
//   node tools\sprite2fl2.js          # sprites\hero2.txt -> games\huiye\hero2_sprite_data.fl
//   node tools\sprite2fl2.js --check  # verify only, do not write
//
// Input format (sprites\hero2.txt):
//   - lines starting with # are comments, ignored;
//   - a blank line separates frames (consecutive blank lines count once);
//   - every pixel row has the same width, every frame the same height;
//   - '0'..'9' = palette index, '.' = 0 (transparent).
// Output: sprite_hero2_load(int *buf) with one assignment per pixel (the v1 compiler has
//   no whole-array initializer, see fact f054), plus sprite_hero2_w / _h / _frames.
// Why element-by-element assignments instead of an array literal: this compiler v1 has no
//   array-wide initialization syntax.
// The generated file is pure ASCII (the compiler accepts ASCII source only).
"use strict";

const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
// --name <sprite> 选源（默认 hero2）：sprites\<name>.txt -> games\huiye\<name>_sprite_data.fl
const args = process.argv.slice(2);
const NAME = args.includes("--name") ? args[args.indexOf("--name") + 1] : "hero2";
if (!/^[a-z][a-z0-9_]*$/.test(NAME)) {
  console.error("sprite2fl2: bad --name " + NAME);
  process.exit(2);
}
const SRC = path.join(ROOT, "sprites", NAME + ".txt");
const OUT = path.join(ROOT, "games", "huiye", NAME + "_sprite_data.fl");

function parseSprite(file) {
  const lines = fs.readFileSync(file, "utf8").split(/\r?\n/);
  const frames = [];
  let cur = [];
  for (const raw of lines) {
    const line = raw.trim();
    if (line.length === 0) {
      if (cur.length > 0) { frames.push(cur); cur = []; }
      continue;
    }
    if (line.startsWith("#")) { continue; }
    if (!/^[0-9.]+$/.test(line)) {
      throw new Error(`${path.basename(file)}: illegal character (only 0-9 and . allowed): ${line}`);
    }
    cur.push(line);
  }
  if (cur.length > 0) { frames.push(cur); }
  if (frames.length === 0) { throw new Error(`${path.basename(file)}: no pixel frames`); }

  const h = frames[0].length;
  const w = frames[0][0].length;
  for (let fi = 0; fi < frames.length; fi++) {
    const fr = frames[fi];
    if (fr.length !== h) {
      throw new Error(`${path.basename(file)}: frame ${fi} has ${fr.length} rows, expected ${h}`);
    }
    for (let y = 0; y < fr.length; y++) {
      if (fr[y].length !== w) {
        throw new Error(`${path.basename(file)}: frame ${fi} row ${y + 1} width ${fr[y].length}, expected ${w}`);
      }
    }
  }
  return { name: NAME, w, h, frames };
}

function genFl(sp) {
  const out = [];
  out.push(`// ${NAME}_sprite_data.fl -- AUTO-GENERATED by tools\\sprite2fl2.js, do not edit by hand.`);
  out.push(`// Source: sprites\\${NAME}.txt (ASCII grid, '.'=0 transparent, 0-9=palette index)`);
  out.push(`// Each sprite: sprite_${NAME}_load(int *buf) element-by-element + sprite_${NAME}_w/_h/_frames.`);
  out.push("");
  out.push(`// ---- ${sp.name}: ${sp.w}x${sp.h}, ${sp.frames.length} frame(s) ----`);
  out.push(`int sprite_${sp.name}_w() { return ${sp.w}; }`);
  out.push(`int sprite_${sp.name}_h() { return ${sp.h}; }`);
  out.push(`int sprite_${sp.name}_frames() { return ${sp.frames.length}; }`);
  out.push(`int sprite_${sp.name}_load(int *buf) {`);
  let idx = 0;
  for (const fr of sp.frames) {
    for (const row of fr) {
      for (const ch of row) {
        const v = ch === "." ? 0 : Number(ch);
        out.push(`  buf[${idx}] = ${v};`);
        idx++;
      }
    }
  }
  out.push("  return 1;");
  out.push("}");
  out.push("");
  return out.join("\n") + "\n";
}

function main() {
  const checkOnly = process.argv.includes("--check");
  if (!fs.existsSync(SRC)) {
    console.error(`sprite2fl2: input not found: ${SRC}`);
    process.exit(1);
  }
  const sp = parseSprite(SRC);
  const text = genFl(sp);
  if (checkOnly) {
    if (fs.existsSync(OUT) && fs.readFileSync(OUT, "utf8") === text) {
      console.log(`sprite2fl2 --check: OK (${sp.w}x${sp.h}, ${sp.frames.length} frames, matches ${path.relative(ROOT, OUT)})`);
      return;
    }
    console.error("sprite2fl2 --check: output is stale, rerun node tools\\sprite2fl2.js");
    process.exit(1);
  }
  fs.writeFileSync(OUT, text, "utf8");
  const total = sp.w * sp.h * sp.frames.length;
  console.log(`sprite2fl2: wrote ${path.relative(ROOT, OUT)} (${sp.w}x${sp.h}, ${sp.frames.length} frames, ${total} pixels)`);
}

main();
