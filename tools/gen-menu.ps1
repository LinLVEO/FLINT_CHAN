# gen-menu.ps1 — 菜单文本 -> FLINT 纯 ASCII 十六进制字节表（第 6 步 6c 用）
# 为什么要有它：FLINT 不支持非 ASCII 字面量/char 数组整体初始化，菜单中文必须逐字节装填；
#   手抄 GBK 码极易错，故由脚本从 UTF-8 文本源生成（源 = apps\m2_float\menu_items.txt）。
# 用法：powershell -NoProfile -ExecutionPolicy Bypass -File tools\gen-menu.ps1
# 输入行格式（TAB 分隔）：<kind>\t<id>\t<key>\t<text>
#   kind = item | popup | helptext | helptitle
#   text 里的字面 "\n" 会被换成真换行（生成物里写回 \n 转义）
# 输出：apps\m2_float\menu_gen.fl（全 ASCII；改文本后重跑本脚本即可）
# 注：本文件含中文 -> 必须带 UTF-8 BOM（PS 5.1 读中文脚本的前提）。
#     另：别用 New-Object System.Collections.Generic.List[string]（PS 5.1 解析不出泛型，实测报
#     "String does not contain a method named Add"）——用数组 += 最稳。
param(
  [string]$In  = "E:\FLINT-lab\apps\m2_float\menu_items.txt",
  [string]$Out = "E:\FLINT-lab\apps\m2_float\menu_gen.fl"
)
$ErrorActionPreference = 'Stop'
$gbk = [System.Text.Encoding]::GetEncoding(936)

function Esc-Lit([string]$s) {
  # 先做 GBK 编码，再按字节决定写法：ASCII 可见字符原样，换行/引号/反斜杠转义，其余 \xNN
  $t = $s -replace '\\n', "`n"
  $bytes = $gbk.GetBytes($t)
  $sb = New-Object System.Text.StringBuilder
  foreach ($b in $bytes) {
    if ($b -eq 0x0A) { [void]$sb.Append('\n') }
    elseif ($b -eq 0x22) { [void]$sb.Append('\"') }
    elseif ($b -eq 0x5C) { [void]$sb.Append('\\') }
    elseif ($b -ge 0x20 -and $b -le 0x7E) { [void]$sb.Append([char]$b) }
    else { [void]$sb.Append('\x' + $b.ToString('X2')) }
  }
  return $sb.ToString()
}

$lines = Get-Content -LiteralPath $In -Encoding UTF8
$buf = @()
$buf += '// menu_gen.fl - AUTO-GENERATED by tools\gen-menu.ps1 (do not edit by hand)'
$buf += '// source: apps\m2_float\menu_items.txt (Chinese text emitted as GBK bytes: \xNN)'
$buf += 'api user32 int AppendMenuA(int, int, int, int);'
$buf += 'api user32 int MessageBoxA(int, int, int, int);'
$helpBody = $null
$helpTitle = $null
$nItem = 0; $nPopup = 0
foreach ($ln in $lines) {
  if ([string]::IsNullOrWhiteSpace($ln)) { continue }
  $p = $ln -split "`t"
  if ($p.Count -lt 3) { throw "行格式不对（需要 TAB 分隔的 kind/id/key/text）：$ln" }
  $kind = $p[0].Trim(); $id = $p[1].Trim(); $key = $p[2].Trim()
  $text = if ($p.Count -ge 4) { $p[3] } else { '' }
  $lit = Esc-Lit $text
  switch ($kind) {
    'item' {
      $buf += "int mid_$key() { return $id; }"
      $buf += "int mt_$key(int *h, int flags) { return AppendMenuA(h, flags, $id, `"$lit`"); }"
      $nItem++
    }
    'popup' {
      $buf += "int mid_$key() { return $id; }"
      $buf += "int mt_pop_$key(int *h, int *sub) { return AppendMenuA(h, 0x10, sub, `"$lit`"); }"
      $nPopup++
    }
    'helptext' { $helpBody = $lit }
    'helptitle' { $helpTitle = $lit }
    default { throw "未知 kind：$kind" }
  }
}
if ($null -eq $helpBody) { throw '输入里没有 helptext 行' }
$buf += '// help box (MessageBoxA: 0x40 = MB_ICONINFORMATION)'
$buf += "int menu_help_box() { return MessageBoxA(0, `"$helpBody`", `"$helpTitle`", 0x40); }"
[System.IO.File]::WriteAllText($Out, ($buf -join "`r`n") + "`r`n", (New-Object System.Text.ASCIIEncoding))

# 自证：生成物必须是纯 ASCII（>127 的字节一个都不许有——这正是这套做法的判据）
$gb = [System.IO.File]::ReadAllBytes($Out)
$hi = 0
foreach ($b in $gb) { if ($b -gt 127) { $hi++ } }
Write-Host ("生成: {0}" -f $Out)
Write-Host ("菜单项 {0} 个 + 子菜单标题 {1} 个；文件 {2} 字节，其中 >127 的字节 = {3}" -f $nItem, $nPopup, $gb.Length, $hi)
if ($hi -ne 0) { throw "生成物里出现非 ASCII 字节：$hi 个" }
