// sprite2fl.js -- 精灵表（ASCII 网格）-> FLINT 字节表（games\huiye\sprite_data.fl）
//
// 用法：
//   node tools\sprite2fl.js                 # 扫 sprites\*.txt，写 games\huiye\sprite_data.fl
//   node tools\sprite2fl.js --check         # 只校验，不写文件（门用）
//
// 输入格式（sprites\<name>.txt）：
//   - 以 # 开头的行是注释，忽略；
//   - 空行分隔帧（连续空行只算一次）；
//   - 每个像素行等宽；每帧等行数；字符 '0'..'9' = 调色板索引，'.' = 0（透明）。
// 输出：每个 sprite 一个 int <name>_load(int *buf) 函数（逐元素赋值），
//   外加 <name>_w / <name>_h / <name>_frames 三个尺寸函数。
// 为什么逐元素赋值而不是数组字面量：本编译器 v1 没有数组整体初始化语法（f054 已钉死）。
"use strict";

const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const SRC_DIR = path.join(ROOT, "sprites");
const OUT = path.join(ROOT, "games", "huiye", "sprite_data.fl");

function parseSprite(file) {
  const lines = fs.readFileSync(file, "utf8").split(/\r?\n/);
  const frames = [];
  let cur = [];
  for (const raw of lines) {
    const line = raw.trim();
    if (line.length === 0) {
      if (cur.length > 0) { frames.push(cur); cur = []; }
      continue;
    }
    if (line.startsWith("#")) { continue; }
    if (!/^[0-9.]+$/.test(line)) {
      throw new Error(`${path.basename(file)}: 非法字符（只允许 0-9 和 .）：${line}`);
    }
    cur.push(line);
  }
  if (cur.length > 0) { frames.push(cur); }
  if (frames.length === 0) { throw new Error(`${path.basename(file)}: 没有像素帧`); }

  const h = frames[0].length;
  const w = frames[0][0].length;
  for (let fi = 0; fi < frames.length; fi++) {
    const fr = frames[fi];
    if (fr.length !== h) {
      throw new Error(`${path.basename(file)}: 帧 ${fi} 行数 ${fr.length} != 首帧 ${h}`);
    }
    for (let y = 0; y < fr.length; y++) {
      if (fr[y].length !== w) {
        throw new Error(`${path.basename(file)}: 帧 ${fi} 第 ${y + 1} 行宽 ${fr[y].length} != ${w}`);
      }
    }
  }
  return { name: path.basename(file, ".txt"), w, h, frames };
}

function genFl(sprites) {
  const out = [];
  out.push("// sprite_data.fl -- AUTO-GENERATED by tools\\sprite2fl.js, do not edit by hand.");
  out.push("// 源：sprites\\*.txt（ASCII 网格，'.'=0 透明，0-9=调色板索引）");
  out.push("// 每个 sprite：<name>_load(int *buf) 逐元素赋值 + <name>_w/_h/_frames 尺寸。");
  out.push("");
  for (const sp of sprites) {
    out.push(`// ---- ${sp.name}: ${sp.w}x${sp.h}, ${sp.frames.length} frame(s) ----`);
    out.push(`int sprite_${sp.name}_w() { return ${sp.w}; }`);
    out.push(`int sprite_${sp.name}_h() { return ${sp.h}; }`);
    out.push(`int sprite_${sp.name}_frames() { return ${sp.frames.length}; }`);
    out.push(`int sprite_${sp.name}_load(int *buf) {`);
    let idx = 0;
    for (const fr of sp.frames) {
      for (const row of fr) {
        for (const ch of row) {
          const v = ch === "." ? 0 : Number(ch);
          out.push(`  buf[${idx}] = ${v};`);
          idx++;
        }
      }
    }
    out.push("  return 1;");
    out.push("}");
    out.push("");
  }
  return out.join("\n") + "\n";
}

function main() {
  const checkOnly = process.argv.includes("--check");
  if (!fs.existsSync(SRC_DIR)) {
    console.error(`sprite2fl: 目录不存在 ${SRC_DIR}`);
    process.exit(1);
  }
  // hero2/hero3/… 由 tools\sprite2fl2.js（--name）单独生成，避免同符号重复定义
  const EXCLUDE = ["hero2", "hero4"];
  const files = fs.readdirSync(SRC_DIR)
    .filter((f) => f.endsWith(".txt") && !EXCLUDE.includes(path.basename(f, ".txt")))
    .sort();
  if (files.length === 0) {
    console.error("sprite2fl: sprites\\ 下没有 .txt");
    process.exit(1);
  }
  const sprites = files.map((f) => parseSprite(path.join(SRC_DIR, f)));
  const text = genFl(sprites);
  if (checkOnly) {
    if (fs.existsSync(OUT) && fs.readFileSync(OUT, "utf8") === text) {
      console.log(`sprite2fl --check: OK（${sprites.length} 个 sprite，与 ${path.relative(ROOT, OUT)} 一致）`);
      return;
    }
    console.error("sprite2fl --check: 生成物过期，请重跑 node tools\\sprite2fl.js");
    process.exit(1);
  }
  fs.writeFileSync(OUT, text, "utf8");
  const total = sprites.reduce((n, s) => n + s.w * s.h * s.frames.length, 0);
  console.log(`sprite2fl: 写入 ${path.relative(ROOT, OUT)}（${sprites.length} 个 sprite，${total} 像素）`);
}

main();
